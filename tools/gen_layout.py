#!/usr/bin/env python3
"""Generate lib/layout.lua from a ReaLayout export of the ReaATS editor window (the screen with a sound in it).

    python3 tools/gen_layout.py tools/reaATS_layout.json

The JSON comes from the layout editor (github.com/tjingboem/ReaLayout, project 'reaats'): a list of elements
{panel, state, id, label, shape, x, y, w, h} in pixels of the default window, 1100 x 640. The opening screen (no sound yet) is NOT part of
this: ATS_Editor.lua keeps drawing that as it always did. The elements ATS_Editor.lua reads are the REQUIRED ids below (the '_s' ones are
used for one file and for a channel set alike; 'plot' and 'plot_s' are the picture without and with the channel row).

Anchors, decided from the position in the default window (the window can be resized):
  - an element whose centre lies right of 72 % of the width hangs on the RIGHT edge (its distance to that edge stays), else on the LEFT;
  - an element whose centre lies below 85 % of the height hangs on the BOTTOM edge, else on the TOP.
  - the picture is different: its margins (left, right, top, bottom) are taken from 'plot', the channel row's height from 'plot_s' minus 'plot',
    and it stretches with the window.
The file lib/layout.lua is overwritten, never edited by hand.
"""
import json
import os
import sys

REF_W, REF_H = 1100, 640
REQUIRED = ["hdr_info_s", "hdr_partial_s", "hdr_selinfo_s", "btn_analyse_s", "btn_export_s", "btn_print_s", "btn_start_s", "btn_audition_s",
            "chk_noise_s", "chk_sine_s", "ch1_led", "ch1_btn", "ch1_slider", "ch2_btn", "btn_stackmode", "plot", "plot_s",
            "btn_maxpart_s", "btn_space_s", "space_slider_s", "space_pct_s", "space_out_s"]


def main():
    if len(sys.argv) < 2:
        print(__doc__)
        sys.exit(2)
    src = sys.argv[1]
    out = sys.argv[2] if len(sys.argv) > 2 else os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "lib", "layout.lua")
    els = {e["id"]: e for e in json.load(open(src, encoding="utf-8"))}
    missing = [i for i in REQUIRED if i not in els]
    if missing:
        print("missing in the layout: " + ", ".join(missing))
        sys.exit(1)
    plot, plot_s = els["plot"], els["plot_s"]
    margins = [plot["x"], REF_W - (plot["x"] + plot["w"]), plot["y"], REF_H - (plot["y"] + plot["h"]), plot_s["y"] - plot["y"]]
    lines = ["-- GENERATED by tools/gen_layout.py from " + os.path.basename(src) + ": do not edit; change the layout in ReaLayout and run the tool again.",
             "-- The editor window with a sound in it, in pixels of the default window (%d x %d); ax / ay say which edge an element hangs on." % (REF_W, REF_H),
             "return {",
             "  ref_w = %d, ref_h = %d," % (REF_W, REF_H),
             "  margins = { %d, %d, %d, %d, %d },        -- left, right, top, bottom of the picture, and the height of the channel row" % tuple(margins),
             "  el = {"]
    for i in REQUIRED:
        e = els[i]
        ax = "r" if e["x"] + e["w"] / 2.0 > REF_W * 0.72 else "l"
        ay = "b" if e["y"] + e["h"] / 2.0 > REF_H * 0.85 else "t"
        lines.append('    %-16s = { x = %d, y = %d, w = %d, h = %d, ax = "%s", ay = "%s" },' % (i, e["x"], e["y"], e["w"], e["h"], ax, ay))
    lines += ["  },", "}", ""]
    with open(out, "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines))
    print("wrote %s (%d elements)" % (out, len(REQUIRED)))


if __name__ == "__main__":
    main()
