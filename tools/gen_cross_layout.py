#!/usr/bin/env python3
"""Generate lib/cross_layout.lua from a ReaLayout export of the ReaATS CROSS page.

    python3 tools/gen_cross_layout.py tools/reaATS_Cross_layout.json

The JSON comes from the layout editor (github.com/tjingboem/ReaLayout, project 'reaats_cross'): a list of elements {panel, state, id, label, shape, x, y, w, h}
in pixels of the default window, 1100 x 640 (the page starts 40 px from the top). lib/cross_page.lua draws and clicks at these places.
Ids: txt_* (texts), btn_* (buttons), lane_a / lane_b (the two lanes; both use the x and width of lane_a for the time scale), ruler, sl_time / sl_freq (sliders).
The label of a button and of the title is the text the page writes on it (so rename it in ReaLayout to rename the button). Elements that are left out use the built-in default place. lib/cross_layout.lua is overwritten, never edited by hand.
"""
import json
import os
import sys

REQUIRED = ["btn_back", "btn_load_a", "btn_load_b", "btn_make", "lane_a", "lane_b", "ruler", "sl_time", "sl_freq"]


def main():
    if len(sys.argv) < 2:
        print(__doc__)
        sys.exit(2)
    src = sys.argv[1]
    out = sys.argv[2] if len(sys.argv) > 2 else os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "lib", "cross_layout.lua")
    els = {e["id"]: e for e in json.load(open(src, encoding="utf-8"))}
    missing = [i for i in REQUIRED if i not in els]
    if missing:
        print("missing in the layout: " + ", ".join(missing))
        sys.exit(1)
    lines = ["-- GENERATED by tools/gen_cross_layout.py from " + os.path.basename(src) + ": do not edit; change the layout in ReaLayout and run the tool again.",
             "-- The CROSS page, in pixels of the default window (1100 x 640). Elements that are not here use the page's own default place.",
             "return {", "  el = {"]
    for i in sorted(els):
        e = els[i]
        label = e.get("label", "").replace("\\", "\\\\").replace('"', '\\"')
        lines.append('    %-18s = { x = %d, y = %d, w = %d, h = %d, label = "%s" },' % (i, e["x"], e["y"], e["w"], e["h"], label))
    lines += ["  },", "}", ""]
    with open(out, "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines))
    print("wrote %s (%d elements)" % (out, len(els)))


if __name__ == "__main__":
    main()
