#!/usr/bin/env python3
"""Generate lib/analysis_layout.lua from a ReaLayout export of the ReaATS Analysis page.

    python3 tools/gen_analysis_layout.py tools/reaATS_Analyses_layout.json

The JSON comes from the layout editor (github.com/tjingboem/ReaLayout, project 'reaats_analysis'): a list of elements {panel, state, id, label, shape,
x, y, w, h} in pixels of the default window, 1100 x 640 (the page starts 40 px from the top). ATS_Editor.lua hands the table to the page
(lib/analysis_page.lua), which draws and clicks everything at these places. The page is not anchored: it is drawn at exactly these places.
Ids: hdr_* (headings), btn_* (buttons), txt_file / txt_fileinfo / txt_result / txt_derived (texts), fld_<key> (a field's box, or a whole switch),
lbl_<key> (a field's label) and unit_<key> (its unit). Elements that are left out of the layout are simply not drawn (see Page:draw).
The file lib/analysis_layout.lua is overwritten, never edited by hand.
"""
import json
import os
import sys

REQUIRED = ["hdr_source", "hdr_window_and_time", "hdr_peaks_and_tracks", "hdr_output", "btn_use_selected_item", "btn_import_sound_file",
            "btn_import_ats_file", "btn_inspect_sound_file", "txt_file", "btn_analyse", "btn_defaults", "btn_editor"]


def main():
    if len(sys.argv) < 2:
        print(__doc__)
        sys.exit(2)
    src = sys.argv[1]
    out = sys.argv[2] if len(sys.argv) > 2 else os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "lib", "analysis_layout.lua")
    els = {}
    for e in json.load(open(src, encoding="utf-8")):
        els[e["id"]] = e
    missing = [i for i in REQUIRED if i not in els]
    if missing:
        print("missing in the layout: " + ", ".join(missing))
        sys.exit(1)
    lines = ["-- GENERATED by tools/gen_analysis_layout.py from " + os.path.basename(src) + ": do not edit; change the layout in ReaLayout and run the tool again.",
             "-- The Analysis page, in pixels of the default window (1100 x 640). Elements that are not here are not drawn.",
             "return {", "  el = {"]
    for i in sorted(els):
        e = els[i]
        lines.append('    %-30s = { x = %d, y = %d, w = %d, h = %d },' % (i, e["x"], e["y"], e["w"], e["h"]))
    lines += ["  },", "}", ""]
    with open(out, "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines))
    print("wrote %s (%d elements)" % (out, len(els)))


if __name__ == "__main__":
    main()
